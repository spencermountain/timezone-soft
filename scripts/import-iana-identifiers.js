import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const archive = process.argv[2]
if (!archive) throw new Error('Usage: node scripts/import-iana-identifiers.js /path/to/tzdata2026d.tar.gz')
const read = name => execFileSync('tar', ['-xOf', archive, name], { encoding: 'utf8', env: { ...process.env, LC_ALL: 'C' } })
const version = read('version').trim()
if (!/^\d{4}[a-z]+$/.test(version)) throw new Error('Unexpected tzdata version')
const zones = new Set()
const links = new Map()
for (const file of ['africa', 'antarctica', 'asia', 'australasia', 'europe', 'northamerica', 'southamerica', 'etcetera', 'backward']) {
  for (const line of read(file).split('\n')) {
    const [kind, target, alias] = line.split('#')[0].trim().split(/\s+/)
    if (kind === 'Zone') zones.add(target)
    if (kind === 'Link') links.set(alias, target)
  }
}
const identifiers = {}
for (const id of [...new Set([...zones, ...links.keys()])].sort()) {
  let target = id
  const seen = new Set()
  while (links.has(target)) {
    if (seen.has(target)) throw new Error(`Cyclic IANA link: ${id}`)
    seen.add(target)
    target = links.get(target)
  }
  if (!zones.has(target)) throw new Error(`Missing IANA target: ${id}`)
  identifiers[id] = target
}
const header = `// IANA tzdata${version} Zone and Link records (main files plus backward).
// Source: https://data.iana.org/time-zones/releases/tzdata${version}.tar.gz
// Generated by scripts/import-iana-identifiers.js; display metadata is maintained separately.
`
writeFileSync(new URL('../data/iana-identifiers.js', import.meta.url), header + 'export default ' + JSON.stringify(identifiers, null, 2) + '\n')
console.log(`Imported ${Object.keys(identifiers).length} IANA identifiers from ${version}`)
