/* eslint-disable no-console */
import fs from 'node:fs'
import { pack } from 'efrt'

import zones, { metas, aliases, patterns, identifiers, countries } from '../../data/index.js'
import { serializeIdentifiers } from '../../test/_lib/serialize-identifiers.js'
import { normalizeAlias } from '../../src/find/_lib/normalize.js'

const options = { strict: false, direction: 'auto', dictionary: true }

const packed = {}
Object.keys(zones).forEach(k => {
  const arr = k.split(/\//)
  const top = arr[0]
  const name = arr.slice(1).join('/')
  packed[top] = packed[top] || {}
  const { dst, names, meta, country } = zones[k]
  let countryNames = countries[country] || []
  if (country) {
    countryNames.push(country)
    countryNames = countryNames.map(normalizeAlias)
  }
  // Country aliases belong to every zone with that country code.
  const words = [...new Set([...names, ...countryNames])].filter(Boolean)
  packed[top][name] = [pack(words, options), meta]
  if (dst) {
    packed[top][name].push(dst)
  }
})

//write it to a file in ./src
const outFile = new URL('../../src/_generated/zones.js', import.meta.url)
fs.mkdirSync(new URL('../../src/_generated/', import.meta.url), { recursive: true })
fs.writeFileSync(outFile, '// Generated by scripts/build/01-pack.js. Edit data/ instead.\nexport default ' + JSON.stringify(packed) + '\n', 'utf8')

// Keep maintenance-only records and fields out of the runtime metadata table.
const usedMetas = new Set(Object.values(zones).map(zone => zone.meta))
const runtimeMetas = Object.fromEntries(Object.entries(metas)
  .filter(([name]) => usedMetas.has(name))
  .map(([name, meta]) => [name, Object.fromEntries(Object.entries(meta)
    .filter(([field]) => ['std', 'dst', 'name', 'long'].includes(field)))]))
fs.writeFileSync(new URL('../../src/_generated/metas.js', import.meta.url), '// Generated by scripts/build/01-pack.js. Edit data/metas.json instead.\nexport default ' + JSON.stringify(runtimeMetas) + '\n', 'utf8')

// Keep JSON loading out of browser code; the identifier table stays compact.
Object.entries({ aliases, 'dst-patterns': patterns }).forEach(([name, data]) => {
  fs.writeFileSync(new URL(`../../src/_generated/${name}.js`, import.meta.url),
    `// Generated by scripts/build/01-pack.js. Edit data/${name}.json instead.\nexport default ${JSON.stringify(data)}\n`)
})
fs.writeFileSync(new URL('../../src/_generated/iana-identifiers.js', import.meta.url),
  '// Generated from data/iana-identifiers.json (IANA tzdata2026d).\n' + serializeIdentifiers(identifiers))

// A country can share a region's name but include zones outside that IANA prefix.
const regionCountries = {}
const regions = new Set(Object.keys(packed).map(region => region.toLowerCase()))
Object.entries(zones).forEach(([id, zone]) => {
  const countryNames = countries[zone.country] || []
  countryNames.forEach(country => {
    const region = normalizeAlias(country)
    if (regions.has(region) && id.split('/')[0].toLowerCase() !== region) {
      regionCountries[region] = regionCountries[region] || []
      regionCountries[region].push(id)
    }
  })
})
fs.writeFileSync(new URL('../../src/_generated/region-countries.js', import.meta.url),
  '// Generated by scripts/build/01-pack.js from zone country codes.\nexport default ' + JSON.stringify(regionCountries) + '\n')

//get filesize
const stats = fs.statSync(outFile)
const size = (stats['size'] / 1000.0).toFixed(1)

console.log('       - packed into  ' + size + 'k\n')
